// Данные уровней. Формат:
//   belt    — вместимость конвейера (число ячеек; ячейки идут плотно, ~25 px на шарик)
//   columns — колонки лотков сверху; первый элемент колонки — передний (его можно нажать)
//   boxes   — коробки снизу одним списком. Раздаются по кругу в 4 стопки: 1-я, 5-я, 9-я… в первую стопку,
//             2-я, 6-я… во вторую и т.д. Верхняя коробка стопки активна, за ней видны ещё две.
// Цвета: R красный, B синий, G зелёный, Y жёлтый, P фиолетовый, O оранжевый
// После правок запускайте: npm run validate  (проверка, что уровень проходим)

export const BOX_SIZE = 3;      // шариков в коробке
export const ACTIVE_BOXES = 4;  // сколько стопок (активных коробок) одновременно

// Раздаёт плоский список коробок по стопкам: стопка i получает коробки i, i+4, i+8…
export function boxStacks(level) {
  const st = Array.from({ length: ACTIVE_BOXES }, () => []);
  level.boxes.forEach((c, i) => st[i % ACTIVE_BOXES].push(c));
  return st;
}

